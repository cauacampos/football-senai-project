import {
  AGILIDADE_MAXIMA_PARA_DESCONTO_EXTRA,
  AGILIDADE_MINIMA_PARA_METADE_DO_DESCONTO,
  AJUSTE_POR_IDADE,
  DESCONTO_EXTRA_AGILIDADE_BAIXA,
  DESCONTO_POR_CONDICAO,
  IDADE_MAXIMA_JOVEM_PROMESSA,
  IDADE_MINIMA_VETERANO,
  PISO_DO_VALOR_EM_CENTAVOS,
  TETO_DO_DESCONTO,
} from './calculo-jogador';

const DESCONTO_DA_CONDICAO = `CASE j.condicao
  WHEN 'MAL_CONDICIONADO' THEN ${DESCONTO_POR_CONDICAO.MAL_CONDICIONADO}
  WHEN 'DOENTE' THEN ${DESCONTO_POR_CONDICAO.DOENTE}
  ELSE 0 END`;

const DESCONTO_COM_AGILIDADE = `CASE
  WHEN j.condicao = 'APTO' THEN 0
  WHEN j.agilidade >= ${AGILIDADE_MINIMA_PARA_METADE_DO_DESCONTO} THEN (${DESCONTO_DA_CONDICAO}) / 2
  WHEN j.agilidade <= ${AGILIDADE_MAXIMA_PARA_DESCONTO_EXTRA} THEN (${DESCONTO_DA_CONDICAO}) + ${DESCONTO_EXTRA_AGILIDADE_BAIXA}
  ELSE ${DESCONTO_DA_CONDICAO} END`;

const AJUSTE_DA_IDADE = `CASE
  WHEN j.idade <= ${IDADE_MAXIMA_JOVEM_PROMESSA} THEN ${AJUSTE_POR_IDADE}
  WHEN j.idade >= ${IDADE_MINIMA_VETERANO} THEN -${AJUSTE_POR_IDADE}
  ELSE 0 END`;

const PERCENTUAL_TOTAL = `GREATEST((${AJUSTE_DA_IDADE}) - (${DESCONTO_COM_AGILIDADE}), ${TETO_DO_DESCONTO})`;

export const VALOR_DE_MERCADO_EM_CENTAVOS_SQL = `GREATEST(
  (ROUND(j.valor_base * 100)::bigint * (10000 + ${PERCENTUAL_TOTAL}) * 2 + 10000) / 20000,
  ${PISO_DO_VALOR_EM_CENTAVOS})`;